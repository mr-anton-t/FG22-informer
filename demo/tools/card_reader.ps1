# Reads the weather card planes from the Pico W (default UART, 115200) and
# rewrites demo\tag\card.h so that demo\tools\flash-card.cmd puts it on the tag.
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\card_reader.ps1 [-Port COM8]

param([string]$Port = "")

$ErrorActionPreference = "Stop"

$OutFile = Join-Path (Join-Path (Split-Path $PSCommandPath) "..\tag") "card.h"

function To-Bytes([string]$Hex) {
  $Hex = ($Hex -replace "\s", "")
  $arr = New-Object System.Collections.Generic.List[System.Byte]
  for ($i = 0; $i -lt $Hex.Length; $i += 2) {
    $arr.Add([System.Convert]::ToByte($Hex.Substring($i, 2), 16))
  }
  return $arr.ToArray()
}

function Write-Plane([string]$Name, [byte[]]$Data) {
  $sb = New-Object System.Text.StringBuilder
  [void]$sb.AppendLine("static const unsigned char $Name[5624] = {")
  $line = "  "
  for ($i = 0; $i -lt $Data.Length; $i++) {
    $line += ("0x{0:X2}," -f $Data[$i])
    if ((($i + 1) % 16) -eq 0) { [void]$sb.AppendLine($line); $line = "  " }
  }
  if ($line.Trim().Length -gt 0) { [void]$sb.AppendLine($line) }
  [void]$sb.AppendLine("};")
  [void]$sb.AppendLine("")
  return $sb.ToString()
}

$ports = [System.IO.Ports.SerialPort]::GetPortNames() | Sort-Object
if (-not $Port) { $Port = $ports[$ports.Length - 1] }
if (-not $Port) {
  Write-Output "No serial ports found; the Pico W default UART0 is the source."
  exit 1
}

Write-Output "Reading from $Port ..."

$sp = New-Object System.IO.Ports.SerialPort($Port, 115200, [System.IO.Ports.Parity]::None, 8, [System.IO.Ports.StopBits]::One)
$sp.Handshake = [System.IO.Ports.Handshake]::None
$sp.Encoding = New-Object System.Text.ASCIIEncoding
$sp.ReadTimeout = 2000
$sp.Open()

$planes = @{}
$sw = New-Object System.Diagnostics.Stopwatch
$sw.Start()
while ($sw.ElapsedMilliseconds -lt 10000 -and $planes.Count -lt 2) {
  try {
    $line = $sp.ReadLine()
  } catch {
    continue
  }
  if ($line -match "^CARD_(BLACK|RED):") {
    $planes[$Matches[1].ToUpper()] = To-Bytes $line.Substring($line.IndexOf(":") + 1)
  }
}
$sp.Close()

if (-not $planes["BLACK"]) { Write-Output "ERROR: no CARD_BLACK received"; exit 1 }
if (-not $planes["RED"]) { Write-Output "ERROR: no CARD_RED received"; exit 1 }

$pBlack = Write-Plane "CARD_BLACK" $planes["BLACK"]
$pRed = Write-Plane "CARD_RED" $planes["RED"]
$header = "/* Generated by tools\card_reader.ps1 from the Pico W. Do not edit. */`n" +
          "#ifndef CARD_H`n#define CARD_H`n" +
          $pBlack + $pRed + "#endif`n"
[System.IO.File]::WriteAllText($OutFile, $header, (New-Object System.Text.UTF8Encoding($false)))
Write-Output "Wrote $OutFile"
